# =========================================================
# CATEGORY PRIORITY
# =========================================================

CATEGORY_PRIORITY = {

    # =====================================
    # BIOLOGICAL SURVIVAL
    # =====================================

    "survival": 100,

    # =====================================
    # HEALTH / SAFETY
    # =====================================

    "health": 90,

    # =====================================
    # OBLIGATIONS
    # =====================================

    "schedule": 75,

    # =====================================
    # SOCIAL
    # =====================================

    "social": 60,

    # =====================================
    # PERSONAL IDENTITY
    # =====================================

    "identity": 40,

    # =====================================
    # ENTERTAINMENT
    # =====================================

    "leisure": 20,

    # =====================================
    # RANDOM IMPULSES
    # =====================================

    "impulse": 10
}

# =========================================================
# FINAL PRIORITY
# =========================================================

def final_priority(i):

    category = i.get(
        "category",
        "impulse"
    )

    category_score = (
        CATEGORY_PRIORITY.get(
            category,
            0
        )
    )

    local_priority = i.get(
        "priority",
        0
    )

    return (
        category_score * 1000
        + local_priority
    )